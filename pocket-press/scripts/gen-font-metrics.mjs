// Builds data/fontMetrics.json from the TTFs in public/fonts.
// The renderer measures text with these tables, so line breaks and text fitting
// come out the same in the browser preview, the Web Worker and Node tests.
// Run after adding a font: node scripts/gen-font-metrics.mjs
import fontkit from "@pdf-lib/fontkit";
import { readFileSync, writeFileSync } from "node:fs";

const fonts = JSON.parse(readFileSync("data/fonts.json", "utf8"));
const ranges = [
  [0x20, 0x7e], [0xa0, 0x17f], [0x1a0, 0x1b0], [0x1ea0, 0x1ef9],
  [0x2010, 0x2027], [0x2030, 0x203a], [0x20ab, 0x20ac], [0x2122, 0x2122],
];

const out = {};
for (const f of fonts) {
  const font = fontkit.create(readFileSync(`public/fonts/${f.file}`));
  const upm = font.unitsPerEm;
  const chars = [];
  const widths = [];
  for (const [a, b] of ranges) {
    for (let cp = a; cp <= b; cp++) {
      const g = font.glyphForCodePoint(cp);
      if (!g || g.id === 0) continue;
      chars.push(String.fromCodePoint(cp));
      widths.push(Math.round((g.advanceWidth / upm) * 1000));
    }
  }
  const capGlyph = font.glyphForCodePoint(0x48); // "H"
  const cap = capGlyph && capGlyph.id !== 0 ? capGlyph.bbox.maxY : font.capHeight || 0.7 * upm;
  out[f.id] = {
    chars: chars.join(""),
    widths,
    ascent: Math.round((font.ascent / upm) * 1000),
    descent: Math.round((font.descent / upm) * 1000),
    capHeight: Math.round((cap / upm) * 1000),
  };
}
writeFileSync("data/fontMetrics.json", JSON.stringify(out));

// @font-face rules so zine previews render with the exact files the PDF embeds.
const css = fonts
  .map((f) => `@font-face {\n  font-family: "pp-${f.id}";\n  src: url("/fonts/${f.file}") format("truetype");\n  font-display: block;\n}`)
  .join("\n\n");
writeFileSync("app/zine-fonts.css", `/* Generated by scripts/gen-font-metrics.mjs. Zine fonts only, never interface text. */\n\n${css}\n`);
console.log("wrote", Object.keys(out).length, "fonts");
