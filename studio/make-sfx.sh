#!/usr/bin/env bash
# Synthesizes the Edit Bay sound effects with ffmpeg (no samples, no licences),
# then writes sfx.js so the Edit Bay page can preview them.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p sfx
gen() { ffmpeg -hide_banner -loglevel error -y -f lavfi -i "$2" -t "$3" -af "$4" -ar 44100 -ac 1 -b:a 96k "sfx/$1.mp3"; }
# Pop: short pitch-dropping sine with a fast decay.
gen pop "aevalsrc='sin(2*PI*t*(900-2600*t))*exp(-28*t)':s=44100" 0.18 "volume=0.9"
# Whoosh: band-passed noise that swells and fades.
gen whoosh "anoisesrc=color=pink:amplitude=0.9:seed=7" 0.55 "bandpass=f=1400:width_type=o:w=1.6,afade=t=in:d=0.3:curve=exp,afade=t=out:st=0.3:d=0.25,volume=1.6"
# Click: tiny filtered tick.
gen click "aevalsrc='(random(1)-0.5)*exp(-180*t)+0.6*sin(2*PI*2200*t)*exp(-90*t)':s=44100" 0.06 "highpass=f=900,volume=1.2"
# Ding: two bell partials with a long tail.
gen ding "aevalsrc='0.5*sin(2*PI*1318*t)*exp(-4*t)+0.25*sin(2*PI*2637*t)*exp(-6*t)+0.12*sin(2*PI*3951*t)*exp(-9*t)':s=44100" 1.0 "volume=0.9"
{
  echo "/* Generated by make-sfx.sh: preview copies of the Edit Bay sound effects. */"
  echo "window.EditBaySFX = {"
  for f in sfx/*.mp3; do n=$(basename "$f" .mp3); echo "  $n: \"data:audio/mpeg;base64,$(base64 -w0 "$f")\","; done
  echo "};"
} > sfx.js
ls -la sfx sfx.js
